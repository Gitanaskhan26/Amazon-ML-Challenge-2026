"""
High-Performance Multilingual Transformer Matcher for Entity Resolution.

Architecture:
    Bi-Encoder with Dense Semantic Representation:
    - Model: 'sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2'
      (Native support for English, Hindi/Indic, French + 50 languages, 384 dimensions)
    - FP16 Half-Precision on GPU (NVIDIA T1000 8GB VRAM)
    - Batched encoding of unique entities (100x faster than cross-encoder)
    - Cosine similarity dot-product on candidate pairs generated by Blocking

Why Bi-Encoder?
    - Encoding 1.73M entities takes ~10-15 minutes on an 8GB GPU.
    - Pairwise dot-product on candidate pairs takes ~1-2 minutes.
    - Total runtime: ~20-30 minutes (Fits easily within competition deadline).
"""

