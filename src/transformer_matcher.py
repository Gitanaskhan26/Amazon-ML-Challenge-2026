try:
    from sentence_transformers import SentenceTransformer
    HAS_SENTENCE_TRANSFORMERS = True
except ImportError:
    pass


DEFAULT_MODEL_NAME = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"
FALLBACK_MODEL_NAME = "sentence-transformers/all-MiniLM-L6-v2"


class DenseSemanticMatcher:
    """
    Multilingual Bi-Encoder for Entity Resolution.
    Encodes business entities into normalized 384-dimensional dense vectors
    and computes semantic similarity scores.
    """

    def __init__(
        self,
        model_name: str = DEFAULT_MODEL_NAME,
        batch_size: int = 256,
        device: Optional[str] = None
    ):
        self.model_name = model_name
        self.batch_size = batch_size

        if not HAS_TORCH:
            raise ImportError(
                "PyTorch is required for DenseSemanticMatcher. "
                "Install via: pip install torch"
            )

        if not HAS_SENTENCE_TRANSFORMERS:
            raise ImportError(
                "sentence-transformers is required for DenseSemanticMatcher. "
                "Install via: pip install sentence-transformers"
            )

        if device is None:
            self.device = "cuda" if torch.cuda.is_available() else "cpu"
        else:
            self.device = device

        logger.info(f"Initializing DenseSemanticMatcher on device: {self.device}")
        if self.device == "cuda":
            gpu_name = torch.cuda.get_device_name(0)
            gpu_mem = torch.cuda.get_device_properties(0).total_memory / (1024 ** 3)
            logger.info(f"  GPU: {gpu_name} ({gpu_mem:.2f} GB VRAM)")

        logger.info(f"Loading transformer model: {self.model_name}...")
        try:
            self.model = SentenceTransformer(self.model_name, device=self.device)
        except Exception as e:
            logger.warning(f"Could not load {self.model_name}: {e}. Trying fallback: {FALLBACK_MODEL_NAME}")
            self.model_name = FALLBACK_MODEL_NAME
            self.model = SentenceTransformer(self.model_name, device=self.device)

        # Use FP16 on GPU for 2x speedup and 50% memory usage
        if self.device == "cuda":
            self.model = self.model.half()
            logger.info("  Enabled FP16 Half-Precision execution on GPU.")

    @staticmethod
    def format_entity_text(rec: Dict) -> str:
        """
        Creates semantic text representation emphasizing discriminative tokens.
        Format: 'Business: {name} | Location: {address}'
        """
        name = rec.get("core_name") or rec.get("norm_name") or rec.get("raw_name") or ""
        addr = rec.get("clean_addr") or rec.get("raw_addr") or ""
        postal = rec.get("postal_code") or ""
        parts = []
        if name:
            parts.append(f"Business: {name}")
        if addr:
            parts.append(f"Location: {addr}")
        if postal:
            parts.append(f"PIN: {postal}")
        return " | ".join(parts) if parts else "Unknown Business"

    def encode_entities(
        self,
        records: Dict[str, Dict],
        show_progress: bool = True
    ) -> Dict[str, np.ndarray]:
        """
        Encodes a dictionary of preprocessed records: {entity_id: record_dict}
        Returns: {entity_id: normalized_embedding_vector (384,)}
        """
        entity_ids = list(records.keys())
        texts = [self.format_entity_text(records[eid]) for eid in entity_ids]
        n_entities = len(entity_ids)

        logger.info(f"Encoding {n_entities:,} unique entities with {self.model_name}...")

        # Encode in batches
        embeddings = self.model.encode(
            texts,
            batch_size=self.batch_size,
            show_progress_bar=show_progress,
            normalize_embeddings=True,  # Unit vectors so dot-product == cosine similarity
            convert_to_numpy=True
        )

        embeddings_dict = {}
        for eid, emb in zip(entity_ids, embeddings):
            embeddings_dict[eid] = emb.astype(np.float32)

        return embeddings_dict

    def score_candidate_pairs(
        self,
        candidate_pairs: List[Tuple[str, str]],
        s1_embeddings: Dict[str, np.ndarray],
        pool_embeddings: Dict[str, np.ndarray],
        batch_size: int = 100000
    ) -> np.ndarray:
        """
        Computes cosine similarity between precomputed embeddings for candidate pairs: [(s1_id, cand_id), ...]
        Returns: 1D numpy array of semantic similarities in range [-1.0, 1.0] (typically [0.0, 1.0]).
        """
        n_pairs = len(candidate_pairs)
        scores = np.zeros(n_pairs, dtype=np.float32)

        logger.info(f"Computing semantic dot-product scores for {n_pairs:,} candidate pairs...")

        # Process in batches to minimize memory allocation
        for start_idx in range(0, n_pairs, batch_size):
            end_idx = min(start_idx + batch_size, n_pairs)
            batch = candidate_pairs[start_idx:end_idx]

            # Vectorized dot product
            emb_dim = 384
            vecs1 = np.zeros((len(batch), emb_dim), dtype=np.float32)
            vecs2 = np.zeros((len(batch), emb_dim), dtype=np.float32)

            for i, (s1_id, cand_id) in enumerate(batch):
                e1 = s1_embeddings.get(s1_id)
                e2 = pool_embeddings.get(cand_id)
                if e1 is not None:
                    vecs1[i] = e1
                if e2 is not None:
                    vecs2[i] = e2

            # Dot product of normalized unit vectors = Cosine Similarity
            batch_sims = np.sum(vecs1 * vecs2, axis=1)
            # Clip numerical artifacts to [-1.0, 1.0]
            scores[start_idx:end_idx] = np.clip(batch_sims, 0.0, 1.0)

        return scores


